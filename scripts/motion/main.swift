// Writes every exercise movement as JSON for the mockup renderer and the GIF recorder:
//   swiftc -O Packages/Overlo4dCore/Sources/Overlo4dCore/Motion.swift Packages/Overlo4dCore/Sources/Overlo4dCore/MotionLibrary.swift \
//       scripts/motion/main.swift -o /tmp/motion-dump && /tmp/motion-dump > scripts/mockups/motion-data.js
import Foundation

func number(_ value: Double) -> String { String(format: "%.1f", value) }
func point(_ p: MotionPoint) -> String { "[\(number(p.x)),\(number(p.y))]" }

var moves: [String] = []
for move in MotionMove.allCases {
    let pattern = move.pattern
    let steps = 20
    let frames = (0...steps).map { step -> String in
        let s = pattern.skeleton(at: Double(step) / Double(steps))
        return "[" + s.points.map(point).joined(separator: ",") + "]"
    }
    let fixtures = pattern.fixtures.map { fixture -> String in
        switch fixture {
        case .block(let x, let y, let width, let height): "[\"block\",\(number(x)),\(number(y)),\(number(width)),\(number(height))]"
        case .line(let a, let b): "[\"line\",\(number(a.x)),\(number(a.y)),\(number(b.x)),\(number(b.y))]"
        case .footPlate: "[\"footPlate\"]"
        }
    }
    let b = pattern.bounds
    moves.append("""
    "\(move.rawValue)":{"view":"\(pattern.view == .side ? "side" : "front")","faceUp":\(pattern.faceUp),"duration":\(pattern.duration),\
    "loadAtHip":\(pattern.loadAtHip),"pulley":\(pattern.pulley.map(point) ?? "null"),\
    "bounds":[\(number(b.minX)),\(number(b.minY)),\(number(b.maxX)),\(number(b.maxY))],\
    "fixtures":[\(fixtures.joined(separator: ","))],"frames":[\(frames.joined(separator: ","))]}
    """)
}
let exercises = MotionLibrary.exercises.sorted { $0.key < $1.key }.map { "\"\($0.key)\":[\"\($0.value.0.rawValue)\",\"\($0.value.1.rawValue)\"]" }
print("// Generated by scripts/motion/main.swift from Overlo4dCore's MotionLibrary.")
print("// Joints per frame: hip, shoulder, head, elbow, hand, knee, ankle, toe, then the far elbow, hand, knee, ankle, toe, shoulder, hip.")
print("const MOTION = {\"moves\":{\n\(moves.joined(separator: ",\n"))\n},\n\"exercises\":{\(exercises.joined(separator: ","))}};")
